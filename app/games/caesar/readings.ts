const keys = Object.keys(readings).sort((a, b) => b.length - a.length);
export interface ReadingPart { text: string; reading?: string }
export function readingParts(text: string): ReadingPart[] {
  const parts: ReadingPart[] = [];
  let offset = 0;
  while (offset < text.length) {
    const key = keys.find(word => text.startsWith(word, offset));
    if (key) { parts.push({ text: key, reading: readings[key] }); offset += key.length; }
    else {
      const literal = text[offset++]!;
      const previous = parts.at(-1);
      if (previous && !previous.reading) previous.text += literal;
      else parts.push({ text: literal });
    }
  }
  return parts;
}
