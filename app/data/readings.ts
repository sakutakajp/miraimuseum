export interface RubySegment { text: string; reading?: string }
const words = Object.keys(readings).sort((a, b) => b.length - a.length);
export function rubySegments(text: string): RubySegment[] {
  const result: RubySegment[] = [];
  let plain = '';
  for (let index = 0; index < text.length;) {
    const word = words.find((word) => text.startsWith(word, index));
    if (word) {
      if (plain) { result.push({ text: plain }); plain = ''; }
      result.push({ text: word, reading: readings[word] });
      index += word.length;
    } else {
      plain += text[index++];
    }
  }
  if (plain) result.push({ text: plain });
  return result;
}
